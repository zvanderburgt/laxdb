#!/usr/bin/env node
/**
 * Bundle netlify/functions/*.ts to plain ESM in netlify/functions-build/.
 *
 * Why pre-bundle at all: `scripts/deploy-netlify.py` ships a zip of built files, and Netlify does not
 * install `node_modules` for a zip deploy — so a function that imports `@netlify/blobs` has to carry
 * its dependencies with it. esbuild does that (it is already a Vite dependency).
 *
 * Usage: node scripts/build-functions.mjs [--watch]
 */
import { build, context } from "esbuild";
import { readdir, rm } from "node:fs/promises";
import { join } from "node:path";
import { execFile } from "node:child_process";
import { promisify } from "node:util";

const run = promisify(execFile);

const ROOT = process.cwd();
const SRC = join(ROOT, "netlify/functions");
const OUT = join(ROOT, "netlify/functions-build");

const options = {
  entryPoints: [join(SRC, "api.ts"), join(SRC, "meta.ts"), join(SRC, "og.ts"), join(SRC, "slice.ts"), join(SRC, "players.ts")],
  outdir: OUT,
  outExtension: { ".js": ".mjs" },
  bundle: true,
  format: "esm",
  platform: "node",
  target: "node20",
  sourcemap: false,
  logLevel: "warning",
  // the share cards carry their own font and rasteriser: a zip deploy installs no node_modules and
  // a fresh function has no network, so the bytes travel inside the bundle
  loader: { ".ttf": "binary", ".wasm": "binary" },
  // the runtime provides these; everything else (@netlify/blobs, satori, resvg) is bundled
  external: ["node:*"],
  banner: { js: "/* generated by scripts/build-functions.mjs — do not edit */" },
};

// the meta function ships the per-entity index inside its bundle, so it is regenerated from
// the dataset on every build and can never describe a player we no longer hold
await run(process.execPath, [join(ROOT, "scripts/gen-entity-index.mjs")]);

await rm(OUT, { recursive: true, force: true });

if (process.argv.includes("--watch")) {
  const ctx = await context(options);
  await ctx.watch();
  console.log(`watching ${SRC} → ${OUT}`);
} else {
  await build(options);
  const files = await readdir(OUT);
  console.log(`built ${files.join(", ")} → netlify/functions-build/`);
}
