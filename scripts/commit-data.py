#!/usr/bin/env python3
"""Commit today's refreshed data to git and push it to origin.

The daily refresh rewrites three generated files under public/. This commits them
so the repo history matches what was deployed, with one deliberate exception:

  public/data.json is a 23 MB single-line JSON. Its "meta.generated" date changes
  on every run even when no player/team/game data moved, and committing 23 MB of
  timestamp churn every morning balloons .git by megabytes a day. So data.json is
  only committed when something other than that date changed. Hash the file with
  the date blanked out and compare against HEAD; if identical, leave it dirty.

Usage:
  python3 scripts/commit-data.py                 # commit + push
  python3 scripts/commit-data.py --no-push       # commit locally only
  python3 scripts/commit-data.py --message "..." # override the commit subject

Exit codes: 0 = committed (or nothing to commit), 1 = git/ssh failure.
"""
import hashlib
import json
import os
import re
import subprocess
import sys
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA_FILES = ["public/data.json", "public/rankings.json", "public/rankings-history.json"]
GENERATED_RE = re.compile(rb'"generated":"[0-9-]*"')
FETCHED_RE = re.compile(rb'"fetched":"[0-9-]*"')


def git(*args, check=True):
    r = subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True)
    if check and r.returncode != 0:
        sys.exit(f"git {' '.join(args)} failed:\n{r.stderr.strip()}")
    return r


def norm_hash(blob: bytes) -> str:
    """Hash with volatile generated/fetched dates blanked, so timestamp-only
    rewrites look identical."""
    return hashlib.sha256(FETCHED_RE.sub(b'"fetched":""', GENERATED_RE.sub(b'"generated":""', blob))).hexdigest()


def head_blob(path: str):
    r = git("show", f"HEAD:{path}", check=False)
    return r.stdout.encode() if r.returncode == 0 else None


def content_changed(path: str, worktree: bytes) -> bool:
    """True when the file differs from HEAD by more than its date stamps."""
    old = head_blob(path)
    if old is None:
        return True
    return norm_hash(old) != norm_hash(worktree)


def main() -> int:
    os.chdir(ROOT)
    args = sys.argv[1:]
    no_push = "--no-push" in args
    message = None
    if "--message" in args:
        message = args[args.index("--message") + 1]

    dirty = git("diff", "--name-only", "--", *DATA_FILES).stdout.split()
    if not dirty:
        print("commit-data: nothing to commit — data files already match HEAD")
        return 0

    staged = []
    for path in dirty:
        if path == "public/data.json":
            with open(path, "rb") as fh:
                blob = fh.read()
            if not content_changed(path, blob):
                print(f"commit-data: {path} changed only its generated date — leaving it unstaged "
                      "(content identical to HEAD)")
                continue
        git("add", "--", path)
        staged.append(path)

    if not staged:
        print("commit-data: only timestamp churn — nothing real to commit")
        return 0

    # Headline numbers, so the history reads like a dataset log.
    summary = ""
    try:
        data = json.load(open(os.path.join(ROOT, "public/data.json")))
        summary = f"{len(data.get('leagues', []))} leagues, {len(data.get('teams', []))} teams, {len(data.get('players', []))} players"
    except Exception:
        pass

    subject = message or f"data: refresh {time.strftime('%Y-%m-%d')}" + (f" ({summary})" if summary else "")
    body = "Files: " + ", ".join(staged) + "\nGenerated by scripts/commit-data.py after the scheduled refresh."

    git("commit", "-q", "-m", subject, "-m", body)
    sha = git("rev-parse", "--short", "HEAD").stdout.strip()
    print(f"commit-data: committed {sha} — {subject}")

    if no_push:
        print("commit-data: --no-push, commit kept local")
        return 0

    branch = git("rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    push = git("push", "-q", "origin", branch, check=False)
    if push.returncode != 0:
        print(f"commit-data: PUSH FAILED (commit {sha} is local only):\n{push.stderr.strip()}")
        return 1
    print(f"commit-data: pushed {sha} to origin/{branch}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
