/**
 * Admin auth. One passphrase, no user table.
 *
 * The SPA decides whether to draw the dock; this file decides whether anything is written. Every
 * mutating route calls `requireSession()` before it parses a body — the client gate is UX only.
 */
import { createHash, createHmac, randomBytes, scryptSync, timingSafeEqual } from "node:crypto";
import { store } from "./store";

export const COOKIE = "laxdb_cms";
export const TTL_SECONDS = 12 * 60 * 60;

const secret = () => {
  const s = process.env.ADMIN_SESSION_SECRET;
  if (!s || s.length < 32) throw new Error("ADMIN_SESSION_SECRET missing or too short (needs 32+ chars)");
  return s;
};

const b64url = (buf: Buffer | string) =>
  Buffer.from(buf).toString("base64").replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");

const fromB64url = (s: string) => Buffer.from(s.replace(/-/g, "+").replace(/_/g, "/"), "base64");

/* ------------------------------- passphrase ------------------------------- */

/**
 * `ADMIN_PASSPHRASE_HASH` is `scrypt$<saltHex>$<hashHex>`, generated by scripts/cms-secret.mjs.
 * The passphrase itself is never stored, never logged and never sent to this service.
 */
export function verifyPassphrase(candidate: string): boolean {
  const packed = process.env.ADMIN_PASSPHRASE_HASH ?? "";
  const [scheme, saltHex, hashHex] = packed.split("$");
  if (scheme !== "scrypt" || !saltHex || !hashHex) return false;
  const expected = Buffer.from(hashHex, "hex");
  let actual: Buffer;
  try {
    actual = scryptSync(candidate.normalize("NFKC"), Buffer.from(saltHex, "hex"), expected.length, {
      N: 16384,
      r: 8,
      p: 1,
      maxmem: 64 * 1024 * 1024,
    });
  } catch {
    return false;
  }
  return actual.length === expected.length && timingSafeEqual(actual, expected);
}

/* --------------------------------- session -------------------------------- */

export interface Session {
  sub: string;
  iat: number;
  exp: number;
}

export function signSession(now = Date.now()): { token: string; session: Session } {
  const session: Session = {
    sub: "editor",
    iat: Math.floor(now / 1000),
    exp: Math.floor(now / 1000) + TTL_SECONDS,
  };
  const payload = b64url(JSON.stringify(session));
  const sig = b64url(createHmac("sha256", secret()).update(payload).digest());
  return { token: `${payload}.${sig}`, session };
}

export function verifySession(token: string | null, now = Date.now()): Session | null {
  if (!token) return null;
  const [payload, sig] = token.split(".");
  if (!payload || !sig) return null;
  let expected: string;
  try {
    expected = b64url(createHmac("sha256", secret()).update(payload).digest());
  } catch {
    // an unconfigured server must fail closed, not 500 on every request
    return null;
  }
  const a = Buffer.from(sig);
  const b = Buffer.from(expected);
  if (a.length !== b.length || !timingSafeEqual(a, b)) return null;
  try {
    const s = JSON.parse(fromB64url(payload).toString("utf8")) as Session;
    if (!s?.exp || s.exp * 1000 < now) return null;
    if (s.sub !== "editor") return null;
    return s;
  } catch {
    return null;
  }
}

/** The write-header the client must echo; derived from the token so it needs no state. */
export const csrfFor = (token: string) => createHash("sha256").update(`cms:${token}`).digest("hex").slice(0, 32);

export function cookieHeader(token: string, maxAge = TTL_SECONDS): string {
  const parts = [
    `${COOKIE}=${token}`,
    "Path=/",
    "HttpOnly",
    "SameSite=Strict",
    `Max-Age=${maxAge}`,
  ];
  // a local dev server is http on localhost; production is always https
  if (process.env.NODE_ENV !== "development" && process.env.CMS_STORE !== "fs") parts.push("Secure");
  return parts.join("; ");
}

export const clearCookie = () => `${COOKIE}=; Path=/; HttpOnly; SameSite=Strict; Max-Age=0`;

export function readCookie(req: Request, name = COOKIE): string | null {
  const raw = req.headers.get("cookie");
  if (!raw) return null;
  for (const part of raw.split(";")) {
    const [k, ...rest] = part.trim().split("=");
    if (k === name) return rest.join("=") || null;
  }
  return null;
}

/** The session behind this request, or null. Never throws on a malformed cookie. */
export function sessionOf(req: Request): Session | null {
  return verifySession(readCookie(req));
}

/* -------------------------------- rate limit ------------------------------- */

const WINDOW_MS = 15 * 60 * 1000;
const MAX_ATTEMPTS = 5;

export const clientIp = (req: Request) =>
  req.headers.get("x-nf-client-connection-ip") ??
  req.headers.get("x-forwarded-for")?.split(",")[0]?.trim() ??
  "local";

/** Returns the seconds to wait, or 0 when the caller may try again. Six failures locks the window. */
export async function tooManyAttempts(ip: string): Promise<number> {
  const kv = store("cms");
  const key = `rl/${createHash("sha256").update(ip).digest("hex").slice(0, 24)}`;
  const raw = await kv.get(key);
  if (!raw) return 0;
  try {
    const { n, reset } = JSON.parse(raw) as { n: number; reset: number };
    if (Date.now() > reset) return 0;
    return n >= MAX_ATTEMPTS ? Math.ceil((reset - Date.now()) / 1000) : 0;
  } catch {
    return 0;
  }
}

export async function recordFailure(ip: string): Promise<void> {
  const kv = store("cms");
  const key = `rl/${createHash("sha256").update(ip).digest("hex").slice(0, 24)}`;
  const now = Date.now();
  let n = 1;
  let reset = now + WINDOW_MS;
  const raw = await kv.get(key);
  if (raw) {
    try {
      const prev = JSON.parse(raw) as { n: number; reset: number };
      if (prev.reset > now) {
        n = prev.n + 1;
        reset = prev.reset;
      }
    } catch {
      /* corrupt counter restarts the window */
    }
  }
  // keep the record a little past the window so a stale read cannot resurrect it
  await kv.set(key, JSON.stringify({ n, reset }));
}

export async function clearFailures(ip: string): Promise<void> {
  await store("cms").del(`rl/${createHash("sha256").update(ip).digest("hex").slice(0, 24)}`);
}

/** A failure should cost the caller time, not the service. */
export const linger = (ms = 1000) => new Promise((r) => setTimeout(r, ms));

export const newSecret = () => randomBytes(32).toString("hex");

/** Is this deployment actually able to sign anyone in? A missing env var is a config error, not a 401. */
export const configured = (): boolean =>
  Boolean(process.env.ADMIN_PASSPHRASE_HASH?.startsWith("scrypt$")) &&
  (process.env.ADMIN_SESSION_SECRET?.length ?? 0) >= 32;
